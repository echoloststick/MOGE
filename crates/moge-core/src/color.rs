pub fn brick_rgb(n: u32) -> [f32; 3] {
    let c = BRICKS.iter().find(|(i, _)| *i == n).map(|(_, c)| *c).unwrap_or([163, 162, 165]);
    [c[0] as f32 / 255.0, c[1] as f32 / 255.0, c[2] as f32 / 255.0]
}

pub fn nearest_brick(rgb: [f32; 3]) -> u32 {
    let d = |c: &[u8; 3]| (0..3).map(|k| (c[k] as f32 / 255.0 - rgb[k]).powi(2)).sum::<f32>();
    BRICKS.iter().min_by(|a, b| d(&a.1).total_cmp(&d(&b.1))).map(|(i, _)| *i).unwrap_or(DEFAULT_BRICK)
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn exact_and_nearest() {
        assert_eq!(nearest_brick(brick_rgb(21)), 21);
        assert_eq!(nearest_brick([0.99, 0.01, 0.01]), 1004);
        assert_eq!(brick_rgb(99999), brick_rgb(194));
    }
}
